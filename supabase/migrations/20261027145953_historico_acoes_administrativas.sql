-- Execute no SQL Editor do Supabase antes de implantar o backend.
BEGIN;
CREATE TABLE IF NOT EXISTS public.atividades_usuarios (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criado_em timestamptz NOT NULL DEFAULT now(),
    usuario_id varchar(64) NOT NULL,
    usuario_nome varchar(150) NOT NULL,
    perfil varchar(50) NOT NULL,
    metodo varchar(10) NOT NULL,
    recurso varchar(255) NOT NULL,
    status integer NOT NULL CHECK (status BETWEEN 100 AND 599)
);
-- IDs podem pertencer a servidores ou cidadãos; não há FK para uma única tabela.
CREATE INDEX IF NOT EXISTS ix_atividades_usuarios_criado_em ON public.atividades_usuarios (criado_em);
CREATE INDEX IF NOT EXISTS ix_atividades_usuarios_usuario_id ON public.atividades_usuarios (usuario_id);
ALTER TABLE public.atividades_usuarios ENABLE ROW LEVEL SECURITY;
-- Leitura autorizada pela API Flask. Sem acesso direto pelo cliente Supabase.
REVOKE ALL ON TABLE public.atividades_usuarios FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.atividades_usuarios_id_seq FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.atividades_usuarios TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.atividades_usuarios_id_seq TO service_role;
ALTER TABLE public.atividades_usuarios
    ADD COLUMN IF NOT EXISTS entidade varchar(50),
    ADD COLUMN IF NOT EXISTS entidade_id integer,
    ADD COLUMN IF NOT EXISTS acao varchar(100),
    ADD COLUMN IF NOT EXISTS detalhes text;
-- Sem FK: o histórico precisa sobreviver à exclusão do registro e do usuário.
CREATE INDEX IF NOT EXISTS ix_atividades_usuarios_entidade_registro
    ON public.atividades_usuarios (entidade, entidade_id, criado_em DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_atividades_usuarios_acoes
    ON public.atividades_usuarios (criado_em DESC, id DESC) WHERE acao IS NOT NULL;
COMMIT;

-- Verificação após a migração.
SELECT column_name, data_type FROM information_schema.columns
WHERE table_schema = 'public' AND table_name = 'atividades_usuarios'
ORDER BY ordinal_position;
SELECT relrowsecurity FROM pg_class WHERE oid = 'public.atividades_usuarios'::regclass;
SELECT id, usuario_nome, entidade, entidade_id, acao, criado_em
FROM public.atividades_usuarios WHERE acao IS NOT NULL ORDER BY id DESC LIMIT 20;

